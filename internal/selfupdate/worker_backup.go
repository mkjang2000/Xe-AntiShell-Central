// Keep a filesystem reserve even when the input tree or competing disk usage
// grows during a backup. tar preserves source identities, ACLs and SELinux labels.
const backupReserve int64 = 128 << 20

var backupName = regexp.MustCompile(`^backup-[0-9]{8}T[0-9]{6}\.[0-9]{9}Z\.tar$`)

func backupBudget(dir string) (int64, error) {
	var fs unix.Statfs_t
	if err := unix.Statfs(dir, &fs); err != nil {
		return 0, err
	}
	avail := int64(fs.Bavail) * int64(fs.Bsize)
	if avail <= backupReserve {
		return 0, errors.New("insufficient updater disk reserve")
	}
	return avail - backupReserve, nil
}
func checkBackupSpace(ctx context.Context, src, dst string) error {
	available, err := backupBudget(dst)
	if err != nil {
		return err
	}
	fi, err := os.Lstat(src)
	if err != nil || !fi.IsDir() {
		return errors.New("central state directory is unavailable")
	}
	dev := fi.Sys().(*syscall.Stat_t).Dev
	var required int64
	err = filepath.WalkDir(src, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		f, err := d.Info()
		if err != nil {
			return err
		}
		if (!f.Mode().IsRegular() && !f.IsDir()) || f.Sys().(*syscall.Stat_t).Dev != dev {
			return errors.New("central state contains a special file, link or separate mount")
		}
		if available-required < 4096 || (f.Mode().IsRegular() && f.Size() > available-required-4096) {
			return errors.New("insufficient free space for a full central state backup")
		}
		required += 4096
		if f.Mode().IsRegular() {
			required += f.Size()
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, name := range []string{"state.json", "central.db"} {
		f, err := os.Lstat(filepath.Join(src, name))
		if err != nil || !f.Mode().IsRegular() {
			return errors.New("central state database or configuration is missing")
		}
	}
	return nil
}
func (systemHost) space(ctx context.Context, dst string) error {
	return checkBackupSpace(ctx, centralState, dst)
}

type archiveWriter struct {
	f          *os.File
	remaining  int64
	sinceCheck int64
}

func (w *archiveWriter) Write(data []byte) (int, error) {
	if w.sinceCheck >= 8<<20 {
		budget, err := backupBudget(filepath.Dir(w.f.Name()))
		if err != nil {
			return 0, err
		}
		w.remaining = min(w.remaining, budget)
		w.sinceCheck = 0
	}
	if int64(len(data)) > w.remaining {
		return 0, errors.New("state archive exceeded disk budget")
	}
	n, e := w.f.Write(data)
	w.remaining -= int64(n)
	w.sinceCheck += int64(n)
	return n, e
}
func backupState(ctx context.Context, src, dir string) (string, error) {
	if err := checkBackupSpace(ctx, src, dir); err != nil {
		return "", err
	}
	budget, err := backupBudget(dir)
	if err != nil {
		return "", err
	}
	tmp, err := os.CreateTemp(dir, ".backup-")
	if err != nil {
		return "", err
	}
	defer tmp.Close()
	defer os.Remove(tmp.Name())
	parent, base := filepath.Dir(src), filepath.Base(src)
	c := command(ctx, "/usr/bin/tar", "--create", "--file=-", "--format=pax", "--pax-option=delete=atime,delete=ctime", "--numeric-owner", "--acls", "--xattrs", "--selinux", "--sparse", "--one-file-system", "--directory", parent, "--", base)
	c.Stdout = &archiveWriter{f: tmp, remaining: budget}
	c.Stderr = io.Discard
	if err = c.Run(); err != nil {
		return "", errors.New("central state archive could not be completed")
	}
	if err = tmp.Sync(); err != nil {
		return "", err
	}
	if err = tmp.Close(); err != nil {
		return "", err
	}
	compare := command(ctx, "/usr/bin/tar", "--compare", "--file", tmp.Name(), "--numeric-owner", "--acls", "--xattrs", "--selinux", "--directory", parent)
	if err = compare.Run(); err != nil {
		return "", errors.New("central state archive differs from the stopped service state")
	}
	name := "backup-" + time.Now().UTC().Format("20060102T150405.000000000Z") + ".tar"
	if err = os.Rename(tmp.Name(), filepath.Join(dir, name)); err != nil {
		return "", err
	}
	if err = syncDir(dir); err != nil {
		return "", err
	}
	return name, nil
}
func (systemHost) backup(ctx context.Context, dir string) (string, error) {
	return backupState(ctx, centralState, dir)
}

// Only remove backups generated by this updater after a newer upgrade and
// readiness check succeed. An interrupted or failed upgrade retains its backup.
func pruneBackups(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	var names []string
	for _, entry := range entries {
		if entry.Type().IsRegular() && backupName.MatchString(entry.Name()) {
			names = append(names, entry.Name())
		}
	}
	if len(names) <= 2 {
		return nil
	}
	for _, name := range names[:len(names)-2] {
		if err = os.Remove(filepath.Join(dir, name)); err != nil {
			return err
		}
	}
	return syncDir(dir)
}
func clearPartial(dir string) {
	items, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	for _, item := range items {
		name := item.Name()
		if item.Type().IsRegular() && (strings.HasPrefix(name, ".job-") || strings.HasPrefix(name, ".backup-") || strings.HasPrefix(name, ".candidate-")) {
			_ = os.Remove(filepath.Join(dir, name))
		}
	}
}
